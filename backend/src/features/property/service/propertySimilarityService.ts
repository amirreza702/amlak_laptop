import type { Property } from "@prisma/client";

/**
 * ============================================================
 * Property Similarity
 * ============================================================
 *
 * محاسبه میزان شباهت دو ملک بر اساس مشخصات ملک.
 *
 * نکته مهم:
 *
 * فاصله جغرافیایی در امتیاز Similarity هیچ نقشی ندارد.
 *
 * فاصله فقط در مرحله Candidate Matching استفاده می‌شود
 * تا مشخص شود کدام املاک وارد مرحله Similarity شوند.
 *
 * ============================================================
 *
 * وزن‌ها:
 *
 * Postal Code    36%
 * Property Type  14%
 * City           14%
 * District       14%
 * Area           14%
 * Rooms           8%
 *
 * مجموع = 100%
 *
 * ============================================================
 */
export const calculatePropertySimilarity = (
  primary: Property,
  candidate: Property
): number => {
  let score = 0;

  /**
   * ==========================================================
   * Postal Code — 36%
   * ==========================================================
   *
   * برابر بودن کدپستی، نشانه بسیار قوی
   * برای یکسان بودن ملک است.
   */
  if (
    primary.postalCode &&
    candidate.postalCode &&
    primary.postalCode === candidate.postalCode
  ) {
    score += 0.36;
  }

  /**
   * ==========================================================
   * Property Type — 14%
   * ==========================================================
   */
  if (
    primary.propertyType ===
    candidate.propertyType
  ) {
    score += 0.14;
  }

  /**
   * ==========================================================
   * City — 14%
   * ==========================================================
   */
  if (primary.city === candidate.city) {
    score += 0.14;
  }

  /**
   * ==========================================================
   * District — 14%
   * ==========================================================
   */
  if (
    primary.district ===
    candidate.district
  ) {
    score += 0.14;
  }

  /**
   * ==========================================================
   * Area — 14%
   * ==========================================================
   *
   * هرچه اختلاف متراژ کمتر باشد،
   * امتیاز این بخش بیشتر خواهد بود.
   *
   * مثال:
   *
   * 100 و 100 → 100%
   * 100 و 90  → 90%
   * 100 و 50  → 50%
   */
  if (
    primary.area !== null &&
    candidate.area !== null
  ) {
    const maxArea = Math.max(
      primary.area,
      candidate.area
    );

    if (maxArea > 0) {
      const difference =
        Math.abs(
          primary.area -
            candidate.area
        ) / maxArea;

      score +=
        0.14 *
        Math.max(
          0,
          1 - difference
        );
    }
  }

  /**
   * ==========================================================
   * Rooms — 8%
   * ==========================================================
   */
  if (
    primary.rooms !== null &&
    candidate.rooms !== null &&
    primary.rooms === candidate.rooms
  ) {
    score += 0.08;
  }

  /**
   * ==========================================================
   * Result
   * ==========================================================
   *
   * چون مجموع ضرایب دقیقاً 1 است،
   * نیازی به Normalization نداریم.
   *
   * خروجی:
   *
   * 0.00 → کمترین شباهت
   * 1.00 → بیشترین شباهت
   */
  return Number(
  Math.min(
    1,
    Math.max(0, score)
  ).toFixed(2)
);
};